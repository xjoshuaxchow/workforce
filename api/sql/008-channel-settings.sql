CREATE TABLE IF NOT EXISTS messaging_settings_versions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), encrypted_config jsonb NOT NULL,
 ctime timestamptz NOT NULL DEFAULT now(),utime timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS messaging_settings_active (
 id uuid PRIMARY KEY DEFAULT '00000000-0000-4000-8000-000000000001', singleton boolean NOT NULL DEFAULT true UNIQUE CHECK(singleton),
 version_id uuid NOT NULL REFERENCES messaging_settings_versions(id),
 ctime timestamptz NOT NULL DEFAULT now(),utime timestamptz NOT NULL DEFAULT now()
);
